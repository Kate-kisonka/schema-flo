// ── Ротация с памятью: не показываем последние N использованных ──────
const MEM_KEY = "sf-companion-mem";

function readMem() {
  try { return JSON.parse(localStorage.getItem(MEM_KEY)) || {}; }
  catch { return {}; }
}
function writeMem(mem) {
  try { localStorage.setItem(MEM_KEY, JSON.stringify(mem)); } catch { /* приватный режим */ }
}

function pickFrom(pool, memKey) {
  if (!pool || pool.length === 0) return "";
  const mem = readMem();
  const recent = Array.isArray(mem[memKey]) ? mem[memKey] : [];
  const windowSize = Math.min(Math.max(pool.length - 1, 0), 3);
  const candidates = pool
    .map((_, i) => i)
    .filter(i => !recent.slice(-windowSize).includes(i));
  const idx = candidates.length > 0
    ? candidates[Math.floor(Math.random() * candidates.length)]
    : Math.floor(Math.random() * pool.length);
  mem[memKey] = [...recent.slice(-(windowSize - 1 > 0 ? windowSize - 1 : 0)), idx];
  writeMem(mem);
  return pool[idx];
}

// Реплика на событие: companionSay("save_day"), companionSay("breath_done")…
export function companionSay(event) {
  return pickFrom(POOLS[event], event);
}

// Приветствие дня с учётом фазы цикла и повторного захода.
// phaseName — русское имя фазы из data.js (getPhase().name).
const PHASE_KEYS = {
  "Менструация":   "menstrual",
  "Фолликулярная": "follicular",
  "Овуляция":      "ovulation",
  "Лютеиновая":    "luteal",
};

export function companionGreet(phaseName, isReturnVisit = false) {
  if (isReturnVisit) return pickFrom(POOLS.greeting_return, "greeting_return");
  const phaseKey = PHASE_KEYS[phaseName];
  const phasePool = phaseKey ? POOLS[`greeting_${phaseKey}`] : [];
  const pool = [...POOLS.greeting, ...(phasePool || [])];
  return pickFrom(pool, "greeting");
}
